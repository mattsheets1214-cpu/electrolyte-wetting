"""Generate tests/fixtures/reference_cases.json from CLOSED-FORM formulas only.

The JavaScript tests (tests/physics.test.js) and the Python tests both check
their solvers against this file, so the two implementations are held to the
same independently computed numbers. Re-run after changing a case:

    python python/make_reference_cases.py
"""
import json
import math
from pathlib import Path

P_L = 101300.0


def pc(sigma, theta, r):
    c = math.cos(math.radians(theta))
    c = 0.0 if abs(c) < 1e-12 else c
    return 2 * sigma * c / r


def case_a(name, **k):
    k.setdefault("dpApplied", 0.0)
    k.setdefault("tau", 1.0)
    p = pc(k["sigma"], k["thetaDeg"], k["r"])
    dp = p + k["dpApplied"]
    if dp <= 0:
        return {"name": name, "inputs": k, "expected": {"fills": False}}
    t = 4 * k["mu"] * (k["tau"] * k["X"]) ** 2 / (k["r"] ** 2 * dp)
    return {"name": name, "inputs": k, "expected": {"fills": True, "pc": p, "tTarget": t}}


def case_b(name, **k):
    k.setdefault("pL", P_L)
    p = pc(k["sigma"], k["thetaDeg"], k["r"])
    P = k["pL"] + p
    if P - k["pg0"] <= 0:
        return {"name": name, "inputs": k, "expected": {"fills": False}}
    beta = k["pg0"] / P
    a = 1 - beta
    lam = 0.95 * a
    t_hat = lam ** 2 - 2 * beta * lam + 2 * beta * a * math.log(a / (a - lam))
    T = 4 * k["mu"] * k["Lp"] ** 2 / (k["r"] ** 2 * P)
    return {"name": name, "inputs": k, "expected": {"fills": True, "fillEq": a, "t95": t_hat * T}}


base = dict(r=0.5e-6, sigma=29.4e-3, thetaDeg=30.0, mu=4.4e-3)
cases = {
    "description": "Closed-form reference values (SI). Generated by python/make_reference_cases.py.",
    "modeA": [
        case_a("baseline 70 um", **base, X=70e-6),
        case_a("baseline 1 cm", **base, X=0.01),
        case_a("baseline 5 cm", **base, X=0.05),
        case_a("5 cm tau 2", **base, X=0.05, tau=2.0),
        case_a("applied 50 kPa, r 2 um", **{**base, "r": 2e-6}, X=0.02, dpApplied=50e3),
        case_a("non-wetting pushed", **{**base, "thetaDeg": 100.0}, X=0.01, dpApplied=50e3),
        case_a("non-wetting no push", **{**base, "thetaDeg": 120.0}, X=0.01),
        case_a("theta 90", **{**base, "thetaDeg": 90.0}, X=0.01),
        case_a("viscous 8 mPa s", **{**base, "mu": 8e-3}, X=0.04),
    ],
    "modeB": [
        case_b("ambient gas", **base, pg0=101.3e3, Lp=70e-6),
        case_b("10 kPa vacuum", **base, pg0=10e3, Lp=70e-6),
        case_b("1 kPa vacuum", **base, pg0=1e3, Lp=70e-6),
        case_b("long pore 1 cm, 30 kPa", **base, pg0=30e3, Lp=0.01),
        case_b("non-wetting, evacuated", **{**base, "thetaDeg": 120.0}, pg0=1e3, Lp=70e-6),
        case_b("gas exceeds drive", **base, pg0=300e3, Lp=70e-6),
    ],
}
out = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "reference_cases.json"
out.write_text(json.dumps(cases, indent=2) + "\n")
print(f"wrote {out}")
